'use strict'

const fs = require('node:fs')
const path = require('node:path')
const importer = require('./recipe-catalog-import')
const pinned = require('./recipe-catalog-source')
const ROOT = path.resolve(__dirname, '..')
function check(value, code) { if (!value) throw new Error(code) }
function json(value) { return JSON.stringify(value, null, 2).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029') + '\n' }
function createCatalog(analysis, review) {
  check(review && review.datasetCommit === pinned.DATASET_COMMIT
    && review.importerVersion === importer.IMPORTER_VERSION && /^\d{4}-\d{2}-\d{2}\.\d+$/.test(review.version), 'CATALOG_REVIEW_VERSION')
  check(analysis.datasetCommit === review.datasetCommit && analysis.importerVersion === review.importerVersion, 'CATALOG_ANALYSIS_VERSION')
  check(typeof review.reviewedAt === 'string' && /^\d{4}-\d{2}-\d{2}T00:00:00\.000Z$/.test(review.reviewedAt)
    && Number.isFinite(Date.parse(review.reviewedAt)) && typeof review.reviewScope === 'string'
    && review.reviewScope.length >= 30 && typeof review.sourceVerification === 'string'
    && review.sourceVerification.includes(pinned.SOURCE_VERIFICATION_COMMIT), 'CATALOG_REVIEW_EVIDENCE')
  check(Array.isArray(review.approved) && review.approved.length > 0 && Array.isArray(review.deferred), 'CATALOG_REVIEW_REQUIRED')
  const available = new Map(analysis.candidates.map(item => [item.record.id, item])); const seen = new Set()
  const records = []; const provenance = []
  for (const item of review.approved) {
    check(!seen.has(item.id), 'CATALOG_REVIEW_DUPLICATE'); seen.add(item.id)
    const candidate = available.get(item.id)
    check(candidate && item.sourceHash === candidate.provenance.source_record_sha256
      && item.recordHash === importer.recordHash(candidate.record)
      && item.sourcePath === candidate.provenance.source_path, 'CATALOG_REVIEW_STALE')
    check(/^[a-f0-9]{40}$/.test(item.sourceBlob) && typeof item.reason === 'string' && item.reason.length >= 30, 'CATALOG_REVIEW_EVIDENCE')
    records.push(JSON.parse(JSON.stringify(candidate.record)))
    provenance.push({ ...candidate.provenance, source_path_verified: true,
      source_verification_blob: item.sourceBlob, review_date: review.reviewedAt,
      review_status: { license: 'verified-fixed-inputs-at-build', structure: 'passed',
        content: 'assistant-editorial-reference-review', health: 'not-clinically-validated' },
      review_reason: item.reason })
  }
  for (const item of review.deferred) {
    check(available.has(item.id) && !seen.has(item.id), 'CATALOG_DEFERRED_INVALID'); seen.add(item.id)
    check(typeof item.reason === 'string' && item.reason.length >= 20, 'CATALOG_REVIEW_EVIDENCE')
  }
  const meta = { version: review.version, count: records.length, candidateCount: analysis.candidates.length,
    reviewedCount: seen.size, deferredCount: review.deferred.length, pendingCount: analysis.candidates.length - seen.size,
    quarantinedCount: analysis.quarantined.length, datasetCommit: pinned.DATASET_COMMIT,
    sourceCommit: 'unknown', sourceVerificationCommit: pinned.SOURCE_VERIFICATION_COMMIT,
    license: 'The Unlicense', licenseSha256: pinned.LICENSE_SHA256,
    dataSha256: importer.recordHash(records), reviewSha256: importer.recordHash(review),
    sourceRepository: 'https://github.com/Anduin2017/HowToCook',
    datasetRepository: 'https://github.com/zkeq/vibe-cook-backend',
    imagePolicy: 'excluded', personalized: false, quantityPolicy: 'verbatim-no-conversion',
    records: provenance.map(item => ({ id: item.dataset_record_path.split('#id=')[1], path: item.source_path })),
  }
  return { meta, records, provenance }
}
function buildFiles(result, license) {
  pinned.INPUTS.slice(0, 2).forEach(spec => importer.verifyBytes(spec.name, license))
  const meta = { ...result.meta, licenseText: license.toString('utf8') }
  return {
    'miniprogram/data/recipe-catalog.js': "'use strict'\n// Generated by scripts/build-recipe-catalog.js; reviewed reference data only.\nmodule.exports = " + json(result.records),
    'miniprogram/data/recipe-catalog-meta.js': "'use strict'\n// Generated source attribution; no network request is made from this module.\nmodule.exports = " + json(meta),
    'docs/recipe-catalog-provenance.json': json({ version: meta.version, reviewSha256: meta.reviewSha256, records: result.provenance }),
    'docs/licenses/vibe-cook-dataset.LICENSE.txt': license.toString('utf8'),
    'docs/licenses/howtocook.LICENSE.txt': license.toString('utf8'),
    'NOTICE': `# Third-party recipe data notices\n\nCatalog ${meta.version}: ${meta.count} reviewed reference recipes; remaining candidates are not included.\n\n` +
      `Structured JSON: [zkeq/vibe-cook-backend, dataset](${meta.datasetRepository}/tree/${meta.datasetCommit}), commit \`${meta.datasetCommit}\`, under **The Unlicense**. ` +
      `Only json/index.json and json/recipes.json were used. No BUSL application code, images, SQLite, LFS or online service is included.\n\n` +
      `Upstream: [HowToCook](${meta.sourceRepository}). The actual upstream commit used to generate the dataset is **unknown**. ` +
      `License/path verification snapshot: \`${meta.sourceVerificationCommit}\`; this is not claimed as the generation commit.\n\n` +
      `Both license texts are retained in docs/licenses. SHA-256: \`${meta.licenseSha256}\`. ` +
      `Per-record paths, hashes, transformations and review limitations: [provenance](docs/recipe-catalog-provenance.json) and [review decisions](docs/recipe-catalog-review.json).\n\n` +
      `Images, nutrition estimates, summaries and formulas are removed; quantities remain text. No clinical, allergy-safety or personal-diet endorsement is made. ` +
      `No personal meals, favorites, shopping or health records are replaced by catalog updates. Attribution is voluntary transparency; The Unlicense does not mandate it.\n`,
  }
}
function main() {
  check(process.argv.length === 2 || (process.argv.length === 3 && process.argv[2] === '--check'), 'CATALOG_BUILD_ARGUMENTS')
  const input = importer.safeDirectory(ROOT, ['.local', 'recipe-catalog', pinned.DATASET_COMMIT, 'inputs'])
  const { index, records } = importer.readInputs(input)
  const review = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/recipe-catalog-review.json'), 'utf8'))
  const result = createCatalog(importer.analyze(index, records), review)
  const files = buildFiles(result, fs.readFileSync(path.join(input, 'dataset-license.txt')))
  // Fixed generated files only. No private config, arbitrary path, database or deployment capability.
  for (const [relative, content] of Object.entries(files)) {
    const dir = path.dirname(relative)
    if (dir !== '.') importer.safeDirectory(ROOT, dir.split('/'))
    const target = path.join(ROOT, relative)
    if (fs.existsSync(target)) {
      const stat = fs.lstatSync(target); check(stat.isFile() && !stat.isSymbolicLink(), 'CATALOG_OUTPUT_LINK')
    }
    if (process.argv[2] === '--check') {
      check(fs.existsSync(target) && fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') === content, 'CATALOG_OUTPUT_DRIFT')
    } else fs.writeFileSync(target, content, 'utf8')
  }
  console.log(JSON.stringify({ catalogVersion: result.meta.version, included: result.records.length,
    deferred: result.meta.deferredCount, pending: result.meta.pendingCount, deployed: false }))
}
if (require.main === module) {
  try { main() } catch (error) { console.error(/^CATALOG_[A-Z_]+$/.test(error.message) ? error.message : 'CATALOG_BUILD_FAILED'); process.exitCode = 1 }
}
module.exports = { createCatalog, buildFiles }
